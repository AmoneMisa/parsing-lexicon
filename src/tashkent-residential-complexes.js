const RESIDENTIAL_CONTEXT_RE = /(?:ж\.?\s*к\.?|жил(?:ой|ого)\s+комплекс|новострой(?:ка|ки)?|residential\s+complex|residence|turar\s+joy|uy[-\s]?joy|majmua|массив)/iu;

function hasLocalResidentialContext(text, start, end) {
  const before = text.slice(Math.max(0, start - 36), start);
  const after = text.slice(end, end + 36);
  return RESIDENTIAL_CONTEXT_RE.test(before) || RESIDENTIAL_CONTEXT_RE.test(after);
}

export function matchTashkentResidentialComplex(value) {
  const text = String(value ?? '');
  if (!text) return null;

  const matches = [];
  for (const entry of TASHKENT_RESIDENTIAL_COMPLEXES) {
    const match = text.match(entry.re);
    if (!match) continue;
    const start = match.index ?? 0;
    const end = start + match[0].length;
    if (entry.ambiguous && !hasLocalResidentialContext(text, start, end)) continue;
    matches.push({ entry, length: match[0].trim().length, start });
  }

  matches.sort((a, b) => b.length - a.length || a.start - b.start);
  return matches[0]?.entry ?? null;
}

export function canonicalTashkentResidentialComplex(value) {
  const direct = findCanonical(value, TASHKENT_RESIDENTIAL_COMPLEXES);
  if (direct) return direct.name;
  return matchTashkentResidentialComplex(value)?.name || null;
}
