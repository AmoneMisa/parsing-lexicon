import { aliasesToRegex } from './normalization.js';

function entry(name, aliases = [], entityType) {
  const all = Object.freeze([...new Set([name, ...aliases].filter(Boolean))]);
  return Object.freeze({
    canonical: name,
    name,
    type: entityType,
    entityType,
    country: 'KZ',
    aliases: all,
    re: aliasesToRegex(all),
  });
}

